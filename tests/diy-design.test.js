import assert from 'node:assert/strict';
import * as THREE from 'three';
import { normalizeDesign, createDesignHistory, loadDesign, saveDesign, MAX_ORNAMENTS } from '../src/diy/design.js';
import { createDisplayTree } from '../src/diy/design-layer.js';
import { createDistantModel, createDistantTree } from '../src/diy/distant-tree.js';
import { createTreeTheme } from '../src/scene/tree-theme.js';
import { DISTANT_SCALE, HANDOFF_DURATION } from '../src/diy/tree-handoff.js';

const spec = { id: 1, type: 'star', color: '#c78b9a', size: 1, position: [1, 2, 0], normal: [0, 0, 0] };
const input = { foliageColor: '#9382a6', title: '<script>hello</script>', engraving: '王小明 Amy', ornaments: [spec] };
const normalized = normalizeDesign(input);
assert.deepEqual(normalized.ornaments[0].normal, [0, 0, 1]);
assert.equal(normalizeDesign(null).foliageColor, '#164d3c');
assert.equal(normalizeDesign(null).engraving, '');
assert.equal(normalizeDesign({ engraving: '名'.repeat(30) }).engraving.length, 16);
assert.equal(normalizeDesign({ foliageColor: 'url(evil)', ornaments: [{ ...spec, position: [NaN, 1, 0] }] }).ornaments.length, 0);
assert.equal(normalizeDesign({ ornaments: Array.from({ length: 70 }, (_, i) => ({ ...spec, id: i + 1 })) }).ornaments.length, MAX_ORNAMENTS);
assert.equal(normalizeDesign({ ornaments: [spec, spec] }).ornaments.length, 1);
const history = createDesignHistory();
history.commit(input); history.commit({ ...input, title: 'A' }, 'title'); history.commit({ ...input, title: 'AB' }, 'title');
assert.equal(history.undo().title, input.title); assert.equal(history.redo().title, 'AB');
const copy = history.value; copy.ornaments[0].position[0] = 99; assert.equal(history.value.ornaments[0].position[0], 1);
let json; const storage = { setItem(k, v) { json = v; }, getItem() { return json; } };
assert.ok(saveDesign(storage, normalized, true)); assert.deepEqual(loadDesign(storage), { design: normalized, active: true });
assert.equal(saveDesign(null, normalized, true), false); assert.equal(loadDesign(null).design, null);
const { tree, layer } = createDisplayTree(null);
const theme = createTreeTheme(tree);
layer.apply(normalized); theme.setBaseColor(normalized.foliageColor); theme.update(1, true);
let foliage; tree.layers[0].traverse(o => { if (o.material) foliage = o.material; });
assert.equal(foliage.color.getHexString(), '9382a6');
assert.ok(tree.animated.slice(0, -1).every(o => !o.visible)); assert.equal(layer.targets.length, 1);
const reused = layer.getItem(1); layer.apply({ ...normalized, ornaments: [{ ...normalized.ornaments[0], color: '#ffffff' }] }); assert.equal(layer.getItem(1), reused);
layer.apply(null); theme.setBaseColor(null); theme.set('classic'); theme.update(1, true);
assert.equal(foliage.color.getHexString(), '164d3c'); assert.ok(tree.animated.every(o => o.visible)); assert.equal(layer.targets.length, 0);
layer.dispose(); theme.dispose();
const bare = createDistantModel(null, true), original = createDistantModel(null, false);
assert.ok(bare.children.length <= 5); assert.ok(original.children.length <= 10);
assert.ok(bare.children.every(o => o.geometry.attributes.position.array.every(Number.isFinite)));
console.log('DIY validation, bounded history, persistence, color restoration and distant batching passed.');

// The distant tree has real world-space depth, a shared ground and fixed size.
globalThis.innerWidth = 1280; globalThis.innerHeight = 900;
const scene = new THREE.Scene(), camera = new THREE.PerspectiveCamera(37, 1280 / 900, .1, 60);
camera.position.set(0, 3, 10); camera.lookAt(0, 2, 0);
const controls = { enabled: true, enableDamping: true, target: new THREE.Vector3(0, 2, 0) };
const canvas = new EventTarget(); canvas.getBoundingClientRect = () => ({ left: 0, top: 0, width: 1280, height: 900 });
const transitions = [];
scene.add(tree.root);
const distant = createDistantTree({ scene, camera, controls, canvas, tree, onActivate() {}, onTransition: value => transitions.push(value) });
distant.appearance(null, true); distant.update(.1, true, false);
let scenery, sceneryCamera; distant.renderBackdrop({ render(s, c) { scenery = s; sceneryCamera = c; } });
const background = scenery.getObjectByName('diy-distant-tree');
assert.ok(background.position.clone().project(sceneryCamera).x > .5);
assert.equal(background.position.y, 0); assert.equal(background.scale.x, DISTANT_SCALE);
const initialFar = background.position.clone(), backgroundView = sceneryCamera.matrixWorld.clone(), backgroundPixel = background.position.clone().project(sceneryCamera); camera.position.x += .5; camera.lookAt(controls.target); distant.update(.1, true, false);
assert.ok(background.position.equals(initialFar), 'foreground controls do not move the scenery');
assert.ok(sceneryCamera.matrixWorld.equals(backgroundView));
assert.ok(background.position.clone().project(sceneryCamera).equals(backgroundPixel), 'background stays at the same screen position');
let pendingOrbit = true; controls.update = () => { if (pendingOrbit) { camera.position.x += .8; pendingOrbit = false; } camera.lookAt(controls.target); };
const displayedCamera = camera.position.clone();
distant.swap(null, false); assert.equal(controls.enabled, false);
assert.equal(tree.root.visible, false, 'replace the expensive live tree only during the turn');
assert.equal(tree.root.parent, null, 'the hidden live hierarchy is not traversed during the turn');
assert.ok(scene.getObjectByName('diy-handoff-incoming').children.length <= 10, 'incoming tree uses batched draws');
assert.ok(camera.position.equals(displayedCamera), 'freezing inertia retains the displayed camera');
assert.equal(controls.enableDamping, false);
const openingPose = tree.root.position.clone();
distant.update(.25, true, false);
assert.ok(tree.root.position.equals(openingPose), 'preparing geometry never consumes the first animation frame');
const shadow = scene.getObjectByName('diy-front-contact');
const foot = new THREE.Vector3(0, -.043 * tree.root.scale.y, 0).applyQuaternion(tree.root.quaternion).add(tree.root.position);
assert.ok(shadow.position.distanceTo(foot) < 1e-8, 'contact follows the actual scaled pedestal instead of staying on an unrelated plane');
assert.ok(Math.abs(shadow.scale.x - 4.3 * tree.root.scale.x) < 1e-8);
assert.ok(new THREE.Vector3(0, 0, 1).applyQuaternion(shadow.quaternion).distanceTo(new THREE.Vector3(0, 1, 0).applyQuaternion(tree.root.quaternion)) < 1e-8);
for (let i = 0; i < Math.ceil(HANDOFF_DURATION / .05) + 2; i++) distant.update(.05, true, false);
assert.equal(distant.isMoving, false); assert.equal(controls.enabled, true); assert.equal(controls.enableDamping, true);
assert.equal(tree.root.visible, true); assert.equal(scene.getObjectByName('diy-handoff-incoming'), undefined);
assert.equal(tree.root.parent, scene);
assert.deepEqual(tree.root.position.toArray(), [0, 0, 0]); assert.equal(tree.root.scale.x, 1);
assert.deepEqual(transitions, [true, false]);
distant.swap(normalized, false); distant.update(.016, true, true);
assert.equal(distant.isMoving, false);
distant.swap(null, false);
globalThis.innerWidth = 667; globalThis.innerHeight = 375;
distant.update(.016, true, false);
assert.equal(distant.isMoving, false, 'orientation changes finish the exchange safely');
assert.equal(controls.enabled, true); assert.equal(controls.enableDamping, true);
distant.swap(null, false); distant.update(.2, true, false); distant.reset();
assert.equal(tree.root.visible, true, 'replaying mid-turn restores the live tree');
assert.equal(scene.getObjectByName('diy-handoff-incoming'), undefined);
distant.update(.01, true, false); distant.swap(null, false);
distant.dispose(); assert.equal(scene.children.length, 1);
assert.equal(tree.root.visible, true, 'disposing mid-turn restores visibility and releases both proxies');
console.log('Distant placement has perspective, an independent camera, reduced motion and bounded resource replacement.');
