import assert from 'node:assert/strict';
import * as THREE from 'three';
import { normalizeDesign, createDesignHistory, loadDesign, saveDesign, MAX_ORNAMENTS } from '../src/diy/design.js';
import { createDisplayTree } from '../src/diy/design-layer.js';
import { createDistantModel, createDistantTree } from '../src/diy/distant-tree.js';
import { createTreeTheme } from '../src/scene/tree-theme.js';

const spec = { id: 1, type: 'star', color: '#c78b9a', size: 1, position: [1, 2, 0], normal: [0, 0, 0] };
const input = { foliageColor: '#9382a6', title: '<script>hello</script>', engraving: '王小明 Amy', ornaments: [spec] };
const normalized = normalizeDesign(input);
assert.deepEqual(normalized.ornaments[0].normal, [0, 0, 1]);
assert.equal(normalizeDesign(null).foliageColor, '#164d3c');
assert.equal(normalizeDesign(null).engraving, '');
assert.equal(normalizeDesign({ engraving: '名'.repeat(30) }).engraving.length, 16);
assert.equal(normalizeDesign({ foliageColor: 'url(evil)', ornaments: [{ ...spec, position: [NaN, 1, 0] }] }).ornaments.length, 0);
assert.equal(normalizeDesign({ ornaments: Array.from({ length: 70 }, (_, i) => ({ ...spec, id: i + 1 })) }).ornaments.length, MAX_ORNAMENTS);
assert.equal(normalizeDesign({ ornaments: [spec, spec] }).ornaments.length, 1);
const history = createDesignHistory();
history.commit(input); history.commit({ ...input, title: 'A' }, 'title'); history.commit({ ...input, title: 'AB' }, 'title');
assert.equal(history.undo().title, input.title); assert.equal(history.redo().title, 'AB');
const copy = history.value; copy.ornaments[0].position[0] = 99; assert.equal(history.value.ornaments[0].position[0], 1);
let json; const storage = { setItem(k, v) { json = v; }, getItem() { return json; } };
assert.ok(saveDesign(storage, normalized, true)); assert.deepEqual(loadDesign(storage), { design: normalized, active: true });
assert.equal(saveDesign(null, normalized, true), false); assert.equal(loadDesign(null).design, null);
const { tree, layer } = createDisplayTree(null);
const theme = createTreeTheme(tree);
layer.apply(normalized); theme.setBaseColor(normalized.foliageColor); theme.update(1, true);
let foliage; tree.layers[0].traverse(o => { if (o.material) foliage = o.material; });
assert.equal(foliage.color.getHexString(), '9382a6');
assert.ok(tree.animated.slice(0, -1).every(o => !o.visible)); assert.equal(layer.targets.length, 1);
const reused = layer.getItem(1); layer.apply({ ...normalized, ornaments: [{ ...normalized.ornaments[0], color: '#ffffff' }] }); assert.equal(layer.getItem(1), reused);
layer.apply(null); theme.setBaseColor(null); theme.set('classic'); theme.update(1, true);
assert.equal(foliage.color.getHexString(), '164d3c'); assert.ok(tree.animated.every(o => o.visible)); assert.equal(layer.targets.length, 0);
layer.dispose(); theme.dispose();
const bare = createDistantModel(null, true), original = createDistantModel(null, false);
assert.ok(bare.children.length <= 5); assert.ok(original.children.length <= 10);
assert.ok(bare.children.every(o => o.geometry.attributes.position.array.every(Number.isFinite)));
console.log('DIY validation, bounded history, persistence, color restoration and distant batching passed.');

// Swaps must finish in elapsed time even when rendering at ten frames/second.
globalThis.innerWidth = 1280; globalThis.innerHeight = 900;
const scene = new THREE.Scene(), camera = new THREE.PerspectiveCamera(37, 1280 / 900, .1, 60);
camera.position.set(0, 3, 10); camera.lookAt(0, 2, 0);
const controls = { enabled: true, target: new THREE.Vector3(0, 2, 0) };
const canvas = new EventTarget(); canvas.getBoundingClientRect = () => ({ left: 0, top: 0, width: 1280, height: 900 });
const label = { hidden: true, offsetWidth: 154, style: {} };
scene.add(tree.root);
const distant = createDistantTree({ scene, camera, controls, canvas, label, tree, onActivate() {} });
distant.appearance(null, true); distant.update(.1, true, false);
assert.equal(label.hidden, false); assert.equal(scene.children.length, 2);
assert.ok(parseFloat(label.style.left) > innerWidth / 2, 'DIY entrance is on the right');
distant.swap(null, false); assert.equal(controls.enabled, false);
const initialAngle = tree.root.rotation.y;
distant.update(1.5, true, false);
assert.ok(tree.root.rotation.y - initialAngle > 2.8, 'incoming tree turns while entering');
assert.ok(tree.root.position.distanceTo(scene.children[1].position) > .5, 'separate arcs avoid intersecting centers');
assert.equal(distant.isMoving, true);
for (let i = 0; i < 16; i++) distant.update(.1, true, false);
assert.equal(distant.isMoving, false); assert.equal(controls.enabled, true);
assert.deepEqual(tree.root.position.toArray(), [0, 0, 0]); assert.equal(tree.root.scale.x, 1);
distant.swap(normalized, false); distant.update(.016, true, true);
assert.equal(distant.isMoving, false); assert.equal(scene.children.length, 2);
distant.dispose(); assert.equal(scene.children.length, 1);
console.log('DIY transitions finish at low frame rates, respect reduced motion and replace distant resources.');
